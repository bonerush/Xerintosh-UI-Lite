#define FONT_W 6
#define FONT_H 8

uint16_t *g_font_fb = NULL;
int16_t  g_font_fb_w = 0;
int16_t  g_font_fb_h = 0;

static void font_fb_init_once(void)
{
    if (g_font_fb == NULL) {
        g_font_fb_w = HAL_SCREEN_WIDTH;
        g_font_fb_h = HAL_SCREEN_HEIGHT;
        g_font_fb = (uint16_t*)calloc(g_font_fb_w * g_font_fb_h, sizeof(uint16_t));
    }
}

static void font_draw_char(int16_t x, int16_t y, char c, uint16_t color)
{
    if (x + FONT_W < 0 || x >= HAL_SCREEN_WIDTH || y + FONT_H < 0 || y >= HAL_SCREEN_HEIGHT) return;
    if (c < 0 || c > 127) return;
    font_fb_init_once();
    const uint8_t *bm = g_font_6x8[(uint8_t)c];
    for (int16_t row = 0; row < FONT_H; row++) {
        uint8_t bits = bm[row];
        for (int16_t col = 0; col < FONT_W; col++) {
            if (bits & (1 << (7 - col))) {
                int16_t px = x + col;
                int16_t py = y + row;
                if (px >= 0 && px < HAL_SCREEN_WIDTH && py >= 0 && py < HAL_SCREEN_HEIGHT) {
                    g_font_fb[py * HAL_SCREEN_WIDTH + px] = color;
                }
            }
        }
    }
}



/**
 * @brief 设置当前字体（native 桩：忽略字体参数）
 */
void hal_set_font(const void* font) {
    (void)font;
}

/**
 * @brief 绘制 ASCII 字符串（native：6×8 位图字体写入字体层）
 */
void hal_draw_string(int16_t x, int16_t y, const char* str, uint16_t color) {
    if (!str) return;
    font_fb_init_once();
    int16_t cx = x;
    int16_t cy = y - FONT_H + 1;
    while (*str) {
        if (*str == '\n') {
            cx = x;
            cy += FONT_H;
            str++;
            continue;
        }
        font_draw_char(cx, cy, *str, color);
        cx += FONT_W + 1;
        str++;
    }
}

/**
 * @brief 获取 ASCII 字符串宽度（native：按 6×8 位图字体计算）
 */
int16_t hal_get_string_width(const char* str) {
    if (!str) return 0;
    size_t len = strlen(str);
    return (int16_t)(len * (FONT_W + 1));
}

/**
 * @brief 获取当前字体高度（native：返回固定值 8）
 */
int16_t hal_get_font_height(void) {
    return FONT_H;
}

